// OCCTSwiftInteraction#77: where each sub-shape of a capped body came from, so the selection on
// the body can follow it through a cap recut.

import OCCTSwift
import OCCTSwiftTools

/// Where a sub-shape of a capped body came from, named against the body's uncut shape.
///
/// A cap is always cut from the uncut shape (`clippingSourceShapes`), so two cuts of one body are
/// related only through it. Naming every sub-shape of a cut by its origin is what lets
/// `remapSelection(acrossRecutOf:)` carry a selected sub-shape from one cut to the next: its
/// images are the sub-shapes of the new cut with the same origin. The uncut body needs no table,
/// since each of its sub-shapes is its own `.source`.
indirect enum CapOrigin: Hashable, Sendable {
    /// The uncut shape's sub-shape of `kind` at `ordinal` in its identity table, which every cut
    /// left alone or divided into this piece.
    case source(kind: ShapeType, ordinal: Int)
    /// Made by the cut at the plane `planeID`, where it crossed the sub-shape `from`: an edge
    /// across a face, or a vertex on an edge. A `nil` `from` is the cap face itself.
    case cut(planeID: String, from: CapOrigin?)
}

/// One cut `cappedShape` made: the splitter run on `input` with `tool`, the face standing for
/// the plane `planeID`, and the splitter's history.
struct CapCutStep {
    let input: Shape
    let tool: Shape
    let history: ShapeHistoryRef
    let planeID: String
}

/// The origin of each sub-shape of a cut's result, looked up by OCCT's `IsSame`.
///
/// Bucketed by `Shape.hashCode`, which is OCCT's `std::hash<TopoDS_Shape>`: it hashes the TShape
/// and the Location and not the orientation, so two shapes `IsSame` treats as one always share a
/// bucket, and `isSame(as:)` inside the bucket settles a collision.
struct CapOriginLookup {
    private var buckets: [Int: [(shape: Shape, origin: CapOrigin)]] = [:]

    private init() {}

    /// The origin of each sub-shape of the result of the last of `steps`, traced back to
    /// `source`.
    ///
    /// A sub-shape a cut left alone keeps its origin, and so does each piece of one it divided
    /// (the splitter's `Modified`). What a cut generated from a sub-shape gets
    /// `.cut(planeID:from:)` that sub-shape's origin, and what is left of the tool face, which is
    /// the cap face, gets `.cut(planeID:from: nil)`. Claims are made in that order and the first
    /// one wins, so a section edge, which the splitter reports as generated by both the face it
    /// crosses and the tool, is named after the face.
    ///
    /// A sub-shape none of that reaches has no origin. The one case known to produce it is the
    /// `fuseAll` that joins several kept pieces, which has no history: it leaves a piece alone
    /// unless two kept pieces touch, and rebuilds what it merges.
    init(tracing source: Shape, through steps: [CapCutStep]) {
        let sourceIdentity = ShapeIdentity(shape: source, graph: nil)
        for (kind, shapes) in Self.tables(of: sourceIdentity) {
            for (ordinal, shape) in shapes.enumerated() {
                guard let shape else { continue }
                assign(shape, .source(kind: kind, ordinal: ordinal))
            }
        }
        for step in steps {
            let input =
                step.input === source
                ? sourceIdentity : ShapeIdentity(shape: step.input, graph: nil)
            self = carried(across: step, of: input)
        }
    }

    /// The origin of `shape`, or `nil` if no cut accounts for it.
    func origin(of shape: Shape) -> CapOrigin? {
        buckets[shape.hashCode]?.first { $0.shape.isSame(as: shape) }?.origin
    }

    /// Records `origin` for `shape` unless it already has one.
    private mutating func assign(_ shape: Shape, _ origin: CapOrigin) {
        let key = shape.hashCode
        if buckets[key]?.contains(where: { $0.shape.isSame(as: shape) }) == true { return }
        buckets[key, default: []].append((shape, origin))
    }

    /// This lookup carried across `step`, whose input's sub-shapes are `input`.
    private func carried(across step: CapCutStep, of input: ShapeIdentity) -> CapOriginLookup {
        var next = CapOriginLookup()
        var generated: [(shape: Shape, origin: CapOrigin)] = []
        for (_, shapes) in Self.tables(of: input) {
            for case let shape? in shapes {
                guard let origin = origin(of: shape) else { continue }
                let record = step.history.record(of: shape)
                if !record.modified.isEmpty {
                    for piece in record.modified { next.assign(piece, origin) }
                } else if !record.isDeleted {
                    next.assign(shape, origin)
                }
                let made = CapOrigin.cut(planeID: step.planeID, from: origin)
                generated += record.generated.map { ($0, made) }
            }
        }
        for entry in generated { next.assign(entry.shape, entry.origin) }
        let tool = step.history.record(of: step.tool)
        for piece in tool.modified + tool.generated {
            next.assign(piece, .cut(planeID: step.planeID, from: nil))
        }
        return next
    }

    /// The three tables of `identity`, lowest dimension first, so a sub-shape generated by both an edge
    /// and a face is named after the edge.
    private static func tables(of identity: ShapeIdentity) -> [(ShapeType, [Shape?])] {
        [
            (.vertex, identity.vertices.shapes.map { Optional($0) }),
            (.edge, identity.edges.shapes),
            (.face, identity.faces.shapes),
        ]
    }
}

/// The origin of every sub-shape of a capped body, in its identity tables' ordinal space.
///
/// `nil` at an ordinal no cut accounts for (see `CapOriginLookup`), and at one whose table entry
/// has no shape.
struct CapOrigins: Sendable {
    let faces: [CapOrigin?]
    let edges: [CapOrigin?]
    let vertices: [CapOrigin?]

    init(identity: ShapeIdentity, lookup: CapOriginLookup) {
        faces = identity.faces.shapes.map { $0.flatMap(lookup.origin(of:)) }
        edges = identity.edges.shapes.map { $0.flatMap(lookup.origin(of:)) }
        vertices = identity.vertices.shapes.map(lookup.origin(of:))
    }

    /// The origins of the sub-shapes of `kind`; empty for a kind with no table.
    func origins(of kind: ShapeType) -> [CapOrigin?] {
        switch kind {
        case .face: faces
        case .edge: edges
        case .vertex: vertices
        default: []
        }
    }
}
